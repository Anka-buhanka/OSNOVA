#include <iostream>
#define MAXINT 1000000000  // "очень большое число"

// функция сортировки слиянием с разделителями MAXINT
// возвращает количество сравнений элементов
int sort(int a[], int n) {
    int cmp = 0;  // счётчик сравнений элементов
    int sz = 2 * n - 1;  // размер расширенного массива n - элементы + n-1 разделители

    // создаём два рабочих массива
    int* A = new int[sz];  // основной - текущее состояние
    int* B = new int[sz];  // вспомогательный - результат слияния

    // заполняем первый массив начальными значениями
    for (int i = 0; i < n; i++) {
        A[2 * i] = a[i];          // исходный элемент на чётной позиции
        if (i < n - 1)
            A[2 * i + 1] = MAXINT;
    }

    bool not_sorted = true;  // флаг "массив ещё не отсортирован"

    // основной цикл сортировки
    while (not_sorted) {
        not_sorted = false;  // предположение, что массив отсортируется
        int p = 0;  // указатель записи во второй массив
        int i = 0;  // указатель чтения из первого массива

        // проходим по всему первому массиву 
        while (i < sz) {
            while (i < sz && A[i] == MAXINT) i++;
            if (i >= sz) break;

            int s1 = i;
            while (i < sz && A[i] != MAXINT) i++;
            int e1 = i;

            while (i < sz && A[i] == MAXINT) i++;

            if (i >= sz) {
                for (int j = s1; j < e1; j++) B[p++] = A[j];
                if (p < sz) B[p++] = MAXINT;
                break;
            }

            int s2 = i;
            while (i < sz && A[i] != MAXINT) i++;
            int e2 = i;

            int i1 = s1;  // указатель на текущий элемент первой группы
            int i2 = s2;  // указатель на текущий элемент второй группы

            // основное слияние
            while (i1 < e1 && i2 < e2) {
                cmp++;
                B[p++] = (A[i1] < A[i2]) ? A[i1++] : A[i2++];
            }
            while (i1 < e1) B[p++] = A[i1++];
            while (i2 < e2) B[p++] = A[i2++];
            B[p++] = MAXINT;
            not_sorted = true;
        }

        // копируем результат из второго массива обратно в первый для следующей итерации
        for (int j = 0; j < sz; j++) A[j] = B[j];
    }

      // копируем отсортированные элементы из первого массива обратно в исходный массив a[]
    int j = 0;  // указатель в исходном массиве a[]
    for (int i = 0; i < sz && j < n; i++)
        if (A[i] != MAXINT) a[j++] = A[i];

    delete[] A;
    delete[] B;

    return cmp;  // возвращаем количество сравнений
}

int main() {
    // тестируем для трёх размеров массива
    for (int n : {1000, 5000, 10000}) {
        // выделяем память под массив
        int* arr = new int[n];

        // заполняем массив случайными числами
        for (int i = 0; i < n; i++) arr[i] = rand();

        // сортируем и получаем количество сравнений
        int cmp = sort(arr, n);
        // добавляем русский язык
        setlocale(LC_ALL, "Rus");
        // выводим результат
        std::cout << "Размер N = " << n
            << ": выполнено " << cmp << " сравнений"
            << std::endl;

        // освобождаем память
        delete[] arr;
    }

    return 0;
}
